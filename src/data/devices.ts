export function normalizeDeviceType(input: LegacyDeviceAlias): DeviceType | null {
  if (input === 'keyboard' || input === 'mouse' || input === 'pc') return 'pc';
  if (input === 'ps5' || input === 'xbox' || input === 'ipad') return input;
  return null;
}

