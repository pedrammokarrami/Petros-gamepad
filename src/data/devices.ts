export function normalizeDeviceType(input: LegacyDeviceAlias | string): DeviceType | null {
  const key = String(input).trim().toLowerCase();
  if (key === 'ps5' || key === 'playstation' || key === 'ps') return 'ps5';
  if (key === 'xbox' || key === 'xsx') return 'xbox';
  if (key === 'pc' || key === 'keyboard' || key === 'mouse') return 'pc';
  if (key === 'ipad' || key === 'ios' || key === 'touch') return 'ipad';
  return null;
}

